#!/usr/bin/env node

// Delivery encoding only: the recipe identity, decoded size and digest stay
// unchanged. Operate on the packaging script's disposable staging directory.
import { createReadStream, createWriteStream } from "node:fs";
import { readdir, readFile, stat, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pipeline } from "node:stream/promises";
import { createGzip } from "node:zlib";

const directory = process.argv[2];
if (!directory) throw new Error("usage: compress-pages-snapshots.mjs STAGED_DIST");
for (const filename of (await readdir(directory)).sort()) {
  if (!/^dolly-[a-z0-9-]+-system\.snapshot$/.test(filename)) continue;
  const snapshot = resolve(directory, filename);
  const metadataPath = snapshot.replace(/-system\.snapshot$/, "-system-snapshot.mjs");
  const source = await readFile(metadataPath, "utf8");
  const match = source.match(/export const DOLLY_SYSTEM_SNAPSHOT = Object\.freeze\(([\s\S]*)\);\s*$/);
  if (!match) throw new Error(`invalid snapshot metadata: ${metadataPath}`);
  const metadata = JSON.parse(match[1]);
  if (metadata.encoding !== undefined || (await stat(snapshot)).size !== metadata.byteLength) {
    throw new Error(`invalid uncompressed snapshot: ${snapshot}`);
  }
  await pipeline(createReadStream(snapshot), createGzip({ level: 6 }),
    createWriteStream(`${snapshot}.gz`, { flags: "wx" }));
  metadata.encoding = "gzip";
  metadata.encodedByteLength = (await stat(`${snapshot}.gz`)).size;
  await writeFile(metadataPath,
    "// Generated by scripts/compress-pages-snapshots.mjs.\n" +
    `export const DOLLY_SYSTEM_SNAPSHOT = Object.freeze(${JSON.stringify(metadata, null, 2)});\n`);
  await unlink(snapshot);
  console.log(`dolly: ${filename}: ${metadata.byteLength} -> ${metadata.encodedByteLength} bytes`);
}
