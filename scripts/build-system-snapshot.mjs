#!/usr/bin/env node

import { spawn } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, rename, rm, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const projectDir = resolve(import.meta.dirname, "..");
const snapshotPath = resolve(projectDir, "dist/dolly-system.snapshot");
const metadataPath = resolve(projectDir, "dist/dolly-system-snapshot.mjs");
const temporarySnapshotPath = resolve(
  projectDir,
  `dist/.dolly-system.snapshot.${process.pid}.tmp`,
);
const temporaryMetadataPath = resolve(
  projectDir,
  `dist/.dolly-system-snapshot.${process.pid}.mjs.tmp`,
);

function runSnapshotBuild() {
  return new Promise((resolveBuild, reject) => {
    const child = spawn(resolve(projectDir, "scripts/test-browser.sh"), [], {
      cwd: projectDir,
      env: {
        ...process.env,
        DOLLY_BROWSER_MODE: "snapshot-export",
        DOLLY_SNAPSHOT_OUTPUT: temporarySnapshotPath,
      },
      stdio: "inherit",
    });
    child.once("error", reject);
    child.once("exit", (status, signal) => {
      if (status === 0) resolveBuild();
      else reject(new Error(
        `Dolly snapshot browser exited with ${signal ? `signal ${signal}` : `status ${status}`}`,
      ));
    });
  });
}

await Promise.all([
  rm(temporarySnapshotPath, { force: true }),
  rm(temporaryMetadataPath, { force: true }),
]);

try {
  await runSnapshotBuild();
  const snapshot = await readFile(temporarySnapshotPath);
  if (snapshot.length < 16 || snapshot.length > 512 * 1024 * 1024 ||
      snapshot.subarray(0, 8).toString("ascii") !== "DOLLYSNP" ||
      snapshot.readUInt32LE(8) !== 1) {
    throw new Error("headless /rebuild produced an invalid Dolly system snapshot");
  }
  const { DOLLY_BUILD_ID } = await import("../dist/dolly-build-id.mjs");
  const sha256 = createHash("sha256").update(snapshot).digest("hex");
  const metadata = `// Generated by scripts/build-system-snapshot.mjs.\n` +
    `export const DOLLY_SYSTEM_SNAPSHOT = Object.freeze(${JSON.stringify({
      buildId: DOLLY_BUILD_ID,
      formatVersion: 1,
      byteLength: snapshot.length,
      sha256,
    }, null, 2)});\n`;
  await writeFile(temporaryMetadataPath, metadata);
  await rename(temporarySnapshotPath, snapshotPath);
  await rename(temporaryMetadataPath, metadataPath);
  console.log(
    `dolly: packaged ${snapshot.length} byte system snapshot ` +
    `(${sha256.slice(0, 16)}…) for ${DOLLY_BUILD_ID}`,
  );
} finally {
  await Promise.all([
    rm(temporarySnapshotPath, { force: true }),
    rm(temporaryMetadataPath, { force: true }),
  ]);
}
