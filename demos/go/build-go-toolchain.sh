#!/usr/bin/env bash
# The Go seed: Go's release source with the Dolly patch, cross-built for
# GOOS=dolly GOARCH=wasm64 on Linux x86_64 by upstream's toolchain of the same
# release, and packaged as the GOROOT that go-sdk installs.
set -euo pipefail
cd "$(dirname -- "${BASH_SOURCE[0]}")/../.."
source config/source-pins.sh
port=build/go-port
source_archive="$(scripts/fetch-pinned-archive.sh go)"
host_archive="$(scripts/fetch-pinned-archive.sh go_host)"
# The process contract's identity, which the linker writes into executables.
digest="$(node -e 'import("./dist/dolly-process-abi.mjs").then(m => console.log(m.DOLLY_PROCESS_ABI_DIGEST))')"
[[ "${digest}" =~ ^[a-f0-9]{64}$ ]]
input_key="$({
  printf '%s\n' dolly-go-seed-1 "${digest}" "${DOLLY_GO_SHA256}" "${DOLLY_GO_HOST_SHA256}"
  sha256sum demos/go/build-go-toolchain.sh demos/go/go-${DOLLY_GO_VERSION}-dolly.patch
} | sha256sum | cut -d' ' -f1)"
if [[ -f "${port}/seed.inputs" && "$(cat "${port}/seed.inputs")" == "${input_key}" &&
      -f "${port}/seed.sha256" ]] && (cd "${port}" && sha256sum --check --status seed.sha256); then
  echo 'dolly: verified cached Go seed'
  exit 0
fi
rm -rf "${port}/host" "${port}/go" "${port}/sdk"
mkdir -p "${port}/host" "${port}/sdk"
tar -xzf "${host_archive}" -C "${port}/host"
tar -xzf "${source_archive}" -C "${port}"
git -C "${port}/go" apply --unsafe-paths -p1 "${PWD}/demos/go/go-${DOLLY_GO_VERSION}-dolly.patch"
{
  printf '// Code generated by demos/go/build-go-toolchain.sh. DO NOT EDIT.\n\npackage wasm\n\n'
  printf "// dollyProcessABIDigest is Dolly's DOLLY_PROCESS_ABI_DIGEST.\n"
  printf 'var dollyProcessABIDigest = [32]byte{%s}\n' "$(sed 's/../0x&, /g; s/, $//' <<< "${digest}")"
} > "${port}/go/src/cmd/link/internal/wasm/zdolly.go"
(cd "${port}/go/src" && env -u GOROOT -u GOPATH GOTOOLCHAIN=local GOROOT_BOOTSTRAP="${PWD}/../../host/go" \
  GOOS=dolly GOARCH=wasm64 ./make.bash -no-banner)
# The GOROOT of a Dolly session: the sources go builds from, the tools for
# dolly/wasm64 and, in bin, the go and gofmt commands for it.
root="${port}/go"
sdk="${port}/sdk/go"
mkdir -p "${sdk}/bin" "${sdk}/pkg"
cp -a "${root}/VERSION" "${root}/go.env" "${root}/LICENSE" "${root}/PATENTS" "${root}/src" "${root}/lib" "${sdk}/"
cp -a "${root}/pkg/include" "${sdk}/pkg/"
mkdir -p "${sdk}/pkg/tool"
cp -a "${root}/pkg/tool/dolly_wasm64" "${sdk}/pkg/tool/"
cp -a "${root}/bin/dolly_wasm64/go" "${root}/bin/dolly_wasm64/gofmt" "${sdk}/bin/"
tar --sort=name --mtime=@0 --owner=0 --group=0 --numeric-owner -C "${port}/sdk" -cf - go |
  gzip -n -9 > "${port}/go-sdk.tar.gz"
(cd "${port}" && sha256sum go-sdk.tar.gz > seed.sha256)
printf '%s\n' "${input_key}" > "${port}/seed.inputs"
echo "dolly: built the Go seed $(cut -c1-16 "${port}/seed.sha256")…"
