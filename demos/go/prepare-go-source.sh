#!/usr/bin/env bash
# Go's pinned release source with the Dolly patch in DIR/go, and in the linker the identities
# of the process contract and of the http@0 module, which it writes into executables:
# demos/go/prepare-go-source.sh DIR
set -euo pipefail
cd "$(dirname -- "${BASH_SOURCE[0]}")/../.."
source config/source-pins.sh
directory="$1"
digest="$(node -e 'import("./dist/dolly-process-abi.mjs").then(m => console.log(m.DOLLY_PROCESS_ABI_DIGEST))')"
http_digest="$(node -e 'import("./host/http/abi.mjs").then(m => console.log(m.DOLLY_HTTP_ABI_DIGEST))')"
[[ "${digest}" =~ ^[a-f0-9]{64}$ && "${http_digest}" =~ ^[a-f0-9]{64}$ ]]
rm -rf "${directory}/go"
mkdir -p "${directory}"
tar -xzf "$(bash scripts/fetch-pinned-archive.sh go)" -C "${directory}"
patch --batch --fuzz=0 --quiet -d "${directory}/go" -p1 < "demos/go/go-${DOLLY_GO_VERSION}-dolly.patch"
{
  # The header the seed's linker was built with: any change to this file changes the linker.
  printf '// Code generated by demos/go/build-go-toolchain.sh. DO NOT EDIT.\n\npackage wasm\n\n'
  printf "// dollyProcessABIDigest is Dolly's DOLLY_PROCESS_ABI_DIGEST.\n"
  printf 'var dollyProcessABIDigest = [32]byte{%s}\n' "$(sed 's/../0x&, /g; s/, $//' <<< "${digest}")"
  printf "\n// dollyHTTPABIDigest is Dolly's DOLLY_HTTP_ABI_DIGEST.\n"
  printf 'var dollyHTTPABIDigest = [32]byte{%s}\n' "$(sed 's/../0x&, /g; s/, $//' <<< "${http_digest}")"
} > "${directory}/go/src/cmd/link/internal/wasm/zdolly.go"
